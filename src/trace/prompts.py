def user_text_turn(text: str) -> list[dict]:
    return [{"type": "text", "text": text}]


def user_image_text_turn(image, text: str, n_images: int = 1) -> list[dict]:
    content: list[dict] = []
    for k in range(n_images):
        img = image[k] if isinstance(image, (list, tuple)) else image
        content.append({"type": "image", "image": img})
    if text:
        content.append({"type": "text", "text": text})
    return content
